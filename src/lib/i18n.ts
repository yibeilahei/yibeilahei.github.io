export function detectLocale(lang?: string): Locale {
  const raw =
    lang ||
    (typeof navigator !== "undefined"
      ? navigator.languages?.[0] || navigator.language
      : "en");
  const lower = String(raw || "en").toLowerCase();
  for (const [prefix, id] of LOCALE_PREFIXES) {
    if (lower === prefix || lower.startsWith(prefix + "-")) return id;
  }
  return "en";
}

export function normalizeLocalePref(value: unknown): LocalePref {
  if (value === "auto") return "auto";
  if (typeof value === "string" && (LOCALES as string[]).includes(value)) {
    return value as Locale;
  }
  return "auto";
}

export function resolveLocale(pref: LocalePref | undefined, lang?: string): Locale {
  if (pref && pref !== "auto") return pref;
  return detectLocale(lang);
}

export function htmlLang(locale: Locale): string {
  if (locale === "zh") return "zh-CN";
  if (locale === "zh-Hant") return "zh-Hant";
  return locale;
}

export function setLocale(locale: Locale) {
  currentLocale = locale;
}

export function getLocale(): Locale {
  return currentLocale;
}

export function t(
  key: MessageKey,
  vars?: Record<string, string | number>,
  locale: Locale = currentLocale,
): string {
  const dict = dictionaries[locale] || dictionaries.en;
  let out = dict[key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(value));
    }
  }
  return out;
}

export function applyDocumentLocale(locale: Locale) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = htmlLang(locale);
  document.documentElement.dir = RTL_LOCALES.has(locale) ? "rtl" : "ltr";
  document.title = t("metaTitle", undefined, locale);
}
